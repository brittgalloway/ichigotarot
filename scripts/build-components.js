#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');

const COMPONENTS_DIR = path.join(__dirname, '..', 'src', 'javascript', 'components');
const WATCH = process.argv.includes('--watch');

function buildOne(file) {
    const name = file.replace('.partial.html', '');
    const srcPath = path.join(COMPONENTS_DIR, file);
    const outPath = path.join(COMPONENTS_DIR, `${name}.generated.js`);
    const $html = fs.readFileSync(srcPath, 'utf8');
    
    const escaped = $html.replace(/\\/g, '\\\\').replace(/` /g, '\\`').replace(/\$\{/g, '\\${');

    const output = `// AUTO-GENERATED by scripts/build-components.js - do not edit directly.
    // Edit ${file} instead, then run: node scripts/build-components.js
     export const markup = \`${escaped}\`
     `;

     fs.writeFileSync(outPath, output);

     console.log(`Built ${name}.generated.js from ${file}`);
}

function buildAll() {
    const files = fs.readdirSync(COMPONENTS_DIR).filter((f) => f.endsWith('.partial.html'));

    if (files.length === 0) {
        console.log('[build-components] No .partial.html files found in', COMPONENTS_DIR);
        return;
    }

    files.forEach(buildOne);
}

buildAll();

if (WATCH) {
    console.log(`[build-components] Watching ${COMPONENTS_DIR} for changes... (Ctrl+C to stop)`);

    let pending = null;

    fs.watch(COMPONENTS_DIR, (eventType, filename) => {
        if (!filename || !filename.endsWith('.partial.html')) return;

        clearTimeout(pending);
        pending = setTimeout(() => {
            try {
                buildOne(filename);
            } catch (err) {
                console.error(err) 
            }
        }, 50)
    })
}

